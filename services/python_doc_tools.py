#!/usr/bin/env python3
"""
ABYX Python Document & Media Tool Suite
Generates verified standard-compliant documents:
- PDF via ReportLab
- DOCX via python-docx
- XLSX with real working formulas via openpyxl
- PPTX via python-pptx
- Images via Pillow (PIL)
- ZIP archives with SHA-256 checksums
"""

import sys
import os
import json
import zipfile
import hashlib

def generate_pdf(output_path, title, paragraphs):
    from reportlab.lib.pagesizes import letter
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    doc = SimpleDocTemplate(output_path, pagesize=letter, leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=54)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=22,
        leading=26,
        textColor=colors.HexColor('#1a1a1a')
    )

    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['BodyText'],
        fontSize=11,
        leading=16,
        textColor=colors.HexColor('#333333')
    )

    story = [Paragraph(title, title_style), Spacer(1, 16)]
    for p in paragraphs:
        story.append(Paragraph(str(p), body_style))
        story.append(Spacer(1, 10))

    doc.build(story)
    return {
        "status": "success",
        "format": "PDF",
        "path": output_path,
        "bytes": os.path.getsize(output_path)
    }

def generate_docx(output_path, title, sections):
    import docx
    from docx.shared import Inches, Pt, RGBColor

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    doc = docx.Document()

    h = doc.add_heading(title, level=0)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0x11, 0x18, 0x27)

    for sec in sections:
        if isinstance(sec, dict):
            sec_title = sec.get("heading", "Section")
            sec_body = sec.get("body", "")
            doc.add_heading(sec_title, level=1)
            doc.add_paragraph(sec_body)
        else:
            doc.add_paragraph(str(sec))

    doc.save(output_path)
    return {
        "status": "success",
        "format": "DOCX",
        "path": output_path,
        "bytes": os.path.getsize(output_path)
    }

def generate_xlsx(output_path, sheet_name, headers, rows, formula_cell=None, formula=None):
    import openpyxl
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_name or "DataSheet"

    # Header style
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")

    ws.append(headers)
    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center")

    for r in rows:
        ws.append(r)

    # Insert working Excel formula if provided
    if formula_cell and formula:
        ws[formula_cell] = formula
        ws[formula_cell].font = Font(bold=True)

    wb.save(output_path)
    return {
        "status": "success",
        "format": "XLSX",
        "path": output_path,
        "bytes": os.path.getsize(output_path)
    }

def generate_pptx(output_path, presentation_title, slides_data):
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    prs = Presentation()

    # Title slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title = slide.shapes.title
    subtitle = slide.placeholders[1]
    title.text = presentation_title
    subtitle.text = "Generated by ABYX Unified AI Agent Platform"

    # Content slides
    bullet_slide_layout = prs.slide_layouts[1]
    for s_data in slides_data:
        slide = prs.slides.add_slide(bullet_slide_layout)
        shapes = slide.shapes
        shapes.title.text = s_data.get("title", "Slide Title")
        tf = shapes.placeholders[1].text_frame
        bullets = s_data.get("bullets", [])
        if bullets:
            tf.text = bullets[0]
            for b in bullets[1:]:
                p = tf.add_paragraph()
                p.text = b
                p.level = 0

    prs.save(output_path)
    return {
        "status": "success",
        "format": "PPTX",
        "path": output_path,
        "bytes": os.path.getsize(output_path)
    }

def generate_image(output_path, width=800, height=500, bg_color="#18181b", text="ABYX Autonomous Agent"):
    from PIL import Image, ImageDraw, ImageFont

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    img = Image.new("RGB", (width, height), color=bg_color)
    draw = ImageDraw.Draw(img)

    # Draw border
    draw.rectangle([10, 10, width - 10, height - 10], outline="#3f3f46", width=2)

    # Draw text
    draw.text((40, height // 2 - 20), text, fill="#f4f4f5")
    img.save(output_path)

    return {
        "status": "success",
        "format": "IMAGE",
        "path": output_path,
        "bytes": os.path.getsize(output_path),
        "dimensions": [width, height]
    }

def manage_zip(action, zip_path, files=None, extract_to=None):
    os.makedirs(os.path.dirname(os.path.abspath(zip_path)), exist_ok=True)
    if action == "create":
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
            file_items = []
            if isinstance(files, list):
                file_items = [(os.path.basename(f), f) for f in files]
            elif isinstance(files, dict):
                file_items = list(files.items())

            for arcname, filepath in file_items:
                if os.path.exists(filepath):
                    z.write(filepath, arcname)
                else:
                    z.writestr(arcname, filepath)

        # Calculate SHA-256
        h = hashlib.sha256()
        with open(zip_path, "rb") as f:
            h.update(f.read())

        return {
            "status": "success",
            "action": "create",
            "path": zip_path,
            "bytes": os.path.getsize(zip_path),
            "sha256": h.hexdigest()
        }
    elif action == "extract":
        target_dir = extract_to or os.path.dirname(zip_path)
        os.makedirs(target_dir, exist_ok=True)
        with zipfile.ZipFile(zip_path, "r") as z:
            z.extractall(target_dir)
            namelist = z.namelist()
        return {
            "status": "success",
            "action": "extract",
            "extractedFiles": namelist,
            "targetDir": target_dir
        }
    elif action == "verify":
        with zipfile.ZipFile(zip_path, "r") as z:
            bad_file = z.testzip()
            is_valid = bad_file is None

        h = hashlib.sha256()
        with open(zip_path, "rb") as f:
            h.update(f.read())

        return {
            "status": "success",
            "valid": is_valid,
            "corruptFile": bad_file,
            "sha256": h.hexdigest()
        }
    else:
        raise ValueError(f"Unknown zip action: {action}")

def main():
    if len(sys.argv) < 2:
        print(json.dumps({"error": "Missing input JSON payload argument"}))
        sys.exit(1)

    payload = json.loads(sys.argv[1])
    tool = payload.get("tool")

    try:
        if tool == "pdf":
            res = generate_pdf(payload["outputPath"], payload.get("title", "Document"), payload.get("paragraphs", []))
        elif tool == "docx":
            res = generate_docx(payload["outputPath"], payload.get("title", "Document"), payload.get("sections", []))
        elif tool == "xlsx":
            res = generate_xlsx(
                payload["outputPath"],
                payload.get("sheetName", "Sheet1"),
                payload.get("headers", ["Col1"]),
                payload.get("rows", []),
                payload.get("formulaCell"),
                payload.get("formula")
            )
        elif tool == "pptx":
            res = generate_pptx(payload["outputPath"], payload.get("title", "Presentation"), payload.get("slides", []))
        elif tool == "image":
            res = generate_image(
                payload["outputPath"],
                payload.get("width", 800),
                payload.get("height", 500),
                payload.get("bgColor", "#18181b"),
                payload.get("text", "ABYX Media Engine")
            )
        elif tool == "zip":
            res = manage_zip(
                payload.get("action", "create"),
                payload["zipPath"],
                payload.get("files"),
                payload.get("extractTo")
            )
        else:
            res = {"error": f"Unknown tool: {tool}"}

        print(json.dumps(res))
    except Exception as e:
        print(json.dumps({"error": str(e)}))
        sys.exit(1)

if __name__ == "__main__":
    main()
